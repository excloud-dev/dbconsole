  async function executeRawQuery(sqlArg?: string, tabIdArg?: string, connectionIdArg?: string, newOffset: number = 0, newLimit?: number | null) {
    const targetTabId = tabIdArg || activeTab
    const targetTab = tabs.find(t => t.id === targetTabId)
    const targetConnectionId = connectionIdArg || targetTab?.connectionId || activeConnection

    if (!targetConnectionId) return

    const offset = newOffset
    const paramValues = (targetTab?.params ?? []).map((p) => {
      if (p.type === "number") return Number(p.value)
      if (p.type === "boolean") return p.value === "true"
      return p.value
    })

    // Resolve SQL: Argument -> Current Tab -> Empty
    let sql = sqlArg
    if (!sql) {
      sql = targetTab?.query || ""
    }
    // Support users who wrap $n in quotes; strip the quotes for execution while keeping param order.
    const sqlToRun = cleanPositionalPlaceholders(sql)

    if (!sqlToRun.trim()) return

    // Strict Read-Only Check
    if (!isReadOnlySql(sqlToRun)) {
      toast({
        variant: "destructive",
        title: "Query Rejected",
        description: "Only read-only queries (SELECT, WITH) are allowed prevention initiated by client console."
      })
      return
    }

    setIsRunning(true)
    setError(null)
    // If this tab had an open stream, tear it down — running a new query
    // means the previous stream is no longer interesting, and leaving it
    // open holds a Postgres client checked out indefinitely.
    void closeStreamForTab(targetTabId)

    try {
      // Clean SQL for wrapping (remove trailing semicolon)
      const cleanSql = sqlToRun.trim().replace(/;+$/, "")
      const hasUserLimit = hasLimitClause(cleanSql)
      const fallbackLimit = hasUserLimit ? undefined : targetTab?.pagination?.limit ?? 100
      const limit = newLimit === undefined ? fallbackLimit : newLimit === null ? undefined : newLimit

      const shouldIncludeCount = offset === 0 || targetTab?.pagination?.total === undefined

      const data = await apiClient.query.run({
        kind: "raw",
        sql: cleanSql,
        originalSql: cleanSql,
        connectionId: targetConnectionId,
        poolMode,
        scopeKey: poolMode === "per-scope" ? targetTabId : undefined,
        params: paramValues,
        limit,
        offset,
        includeCount: shouldIncludeCount,
      })

      const sqlDisplay = renderSqlWithParams(cleanSql, paramValues)
      setResultsByTab((prev) => ({ ...prev, [targetTabId]: { ...data, sqlDisplay } }))

      // Show success toast with metrics
      toast({
        title: "Query executed",
        description: `${data.rows.length} rows • ${data.durationMs}ms`,
      })

      // Update tab pagination state
      setTabs(prev => prev.map(t => {
        if (t.id === targetTabId) {
          return {
            ...t,
            connectionId: targetConnectionId,
            pagination: {
              limit,
              offset,
              total: data.totalCount ?? t.pagination?.total ?? data.rows?.length
            }
          }
        }
        return t
      }))

    } catch (e: any) {
      console.error("Failed to run query", e)
      const detail = asQueryErrorBody(e)
      setError(detail?.error ?? e?.message ?? "Failed to run query")
      toast({
        variant: "destructive",
        title: "Query failed",
        description: detail?.error ?? e?.message ?? "Failed to run query",
      })
    } finally {
      setIsRunning(false)
    }
  }

  // ---- Streaming -----------------------------------------------------------
  //
  // When a bounded query gets clipped to DBCONSOLE_MAX_ROWS the user can opt
  // into streaming via the truncation banner. We re-run the same SQL through
  // /api/query/stream/open, replace the bounded result with the first batch,
  // and let "Load more" pull subsequent batches via /next. The stream is held
  // open server-side until the user closes it, runs a new query in the same
