const GENERATOR_TEMPLATE_PREFIX = "-- dbconsole:generator "

function encodeGeneratorTemplate(config: { mode: GeneratorMode; table: { schema: string; name: string }; roles?: Record<string, "set" | "where"> }): string {
  return `${GENERATOR_TEMPLATE_PREFIX}${JSON.stringify({ version: 1, kind: "generator", ...config })}`
}

function decodeGeneratorTemplate(sqlTemplate: string): { mode: GeneratorMode; table: { schema: string; name: string }; roles?: Record<string, "set" | "where"> } | null {
  if (!sqlTemplate.startsWith(GENERATOR_TEMPLATE_PREFIX)) return null
  const raw = sqlTemplate.slice(GENERATOR_TEMPLATE_PREFIX.length)
  try {
    const parsed = JSON.parse(raw)
    if (parsed?.kind !== "generator") return null
    if (parsed?.version !== 1) return null
    if (!parsed?.mode || !parsed?.table?.schema || !parsed?.table?.name) return null
    return { mode: parsed.mode, table: parsed.table, roles: parsed.roles }
  } catch {
    return null
  }
}

const cleanPositionalPlaceholders = (sql: string): string =>
  sql.replace(/(['"])\$(\d+)\1/g, (_m, _quote, num) => `$${num}`)

const deriveParamLabels = (sql: string, maxIndex: number): string[] => {
  const labels: string[] = Array.from({ length: maxIndex }, () => "")
  const regex = /([\w."`.]+)\s*(?:=|<>|!=|<|>|<=|>=|LIKE|ILIKE|IN)\s*\$(\d+)/gi
  let match: RegExpExecArray | null
  while ((match = regex.exec(sql))) {
    const column = match[1]?.replace(/["`]/g, "")
    const idx = Number(match[2]) - 1
    if (idx >= 0 && idx < maxIndex && column) {
      labels[idx] = column
    }
  }
  return labels
}

function getErrorInfo(e: any): { status?: number; body?: any; message: string } {
  if (e instanceof ApiError) return { status: e.status, body: e.body, message: e.message }

  const status = typeof e?.status === "number" ? e.status : undefined
  const body = e?.body
  const message =
    typeof e?.message === "string"
      ? e.message
      : typeof body?.error === "string"
        ? body.error
        : "Unknown error"

  return { status, body, message }
}

const toSqlLiteral = (v: unknown): string => {
  if (v === null || v === undefined) return "NULL"
  if (typeof v === "number" || typeof v === "bigint") return String(v)
  if (typeof v === "boolean") return v ? "TRUE" : "FALSE"
  const s = String(v).replace(/'/g, "''")
  return `'${s}'`
}

const renderSqlWithParams = (sql: string, params: unknown[]): string =>
  sql.replace(/\$(\d+)/g, (_m, idx) => {
    const i = Number(idx) - 1
    return toSqlLiteral(params[i] ?? null)
  })

const escapeRegex = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$")

const buildGeneratorParams = (
  schema: SchemaGraph | null,
  table: { schema: string; name: string },
  mode: GeneratorMode,
  roles?: Record<string, "set" | "where">,
): GeneratorParamState[] => {
  if (!schema) return []
  const cols = schema.columns.filter((c) => c.table.schema === table.schema && c.table.name === table.name)
  const pkSet = new Set(
    schema.primaryKeys
      .filter((pk) => pk.table.schema === table.schema && pk.table.name === table.name)
      .map((pk) => pk.columnName),
  )

  return cols.map((c) => {
    const isPk = pkSet.has(c.name)
    const role = mode === "update" ? (roles?.[c.name] ?? (isPk ? "where" : "set")) : undefined
    return {
      name: c.name,
      dataType: c.dataType,
      inputType: guessParamType(c.dataType),
      isNullable: c.isNullable,
      isAuto: isAutoGeneratedColumn(c),
      isPk,
      role,
      overrideAuto: false,
      isNull: false,
      value: "",
    }
  })
}

const buildGeneratorNamedQuery = (tab: Tab): NamedQuery | null => {
  if (!tab.isGenerator || !tab.generator) return null
  return {
    id: `generator-${tab.id}`,
    name: tab.name,
    description: tab.generator.mode === "insert"
      ? "Empty fields are skipped. Auto-generated columns are skipped unless overridden."
      : "Empty fields are skipped. Mark columns as WHERE to target rows safely.",
    query: "",
    parameters: tab.generator.params.map((p) => ({ name: p.name, type: p.inputType })),
  }
}

const buildGeneratorParamMeta = (tab: Tab): Record<string, NamedQueryParamMeta> => {
  if (!tab.isGenerator || !tab.generator) return {}
  return tab.generator.params.reduce<Record<string, NamedQueryParamMeta>>((acc, p) => {
    acc[p.name] = {
      dataType: p.dataType,
      isNullable: p.isNullable,
      isAuto: p.isAuto,
      isPk: p.isPk,
      role: p.role,
      overrideAuto: p.overrideAuto,
      isNull: p.isNull,
    }
    return acc
  }, {})
}


